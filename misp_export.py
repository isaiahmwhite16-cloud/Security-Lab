#!/usr/bin/env python3
"""
Export IOCs from MISP to Pi-hole and Suricata.

  Pi-hole  -> lists/misp-iocs.txt        (one domain per line; add it as an adlist)
  Suricata -> suricata/rules/misp.rules  (rules generated by MISP's own Suricata export)

Only published events and attributes flagged "to_ids" are exported, and attributes
that match a MISP warninglist (known-good domains) are filtered out.

Usage:
  python misp_export.py             # write both files
  python misp_export.py --days 7    # only IOCs from events published in the last 7 days
  python misp_export.py --reload    # also reload Pi-hole gravity and Suricata rules
"""

import argparse
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import requests
import urllib3
from dotenv import load_dotenv

load_dotenv()

MISP_URL = os.getenv("MISP_URL")
MISP_API_KEY = os.getenv("MISP_API_KEY")
MISP_VERIFY_SSL = os.getenv("MISP_VERIFY_SSL", "True").lower() == "true"

if not (MISP_URL and MISP_API_KEY):
    sys.exit("Missing MISP_URL or MISP_API_KEY in .env")

if not MISP_VERIFY_SSL:
    urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)

PIHOLE_LIST = Path("lists/misp-iocs.txt")
SURICATA_RULES = Path("suricata/rules/misp.rules")

# In this lab Suricata only sees the DNS lookups that reach Pi-hole, so only domain-style
# IOCs can fire. Add types such as "ip-dst" if you point Suricata at traffic that has them.
DOMAIN_TYPES = ["domain", "hostname"]

DOMAIN_RE = re.compile(r"^(?:[a-z0-9_-]+\.)+[a-z0-9-]{2,}$")


def misp_search(return_format, types, days=None):
    """Call MISP's attribute restSearch and return the raw text response."""
    body = {
        "returnFormat": return_format,
        "type": types,
        "to_ids": 1,
        "published": 1,
        "enforceWarninglist": 1,
    }
    if days:
        body["last"] = f"{days}d"

    response = requests.post(
        f"{MISP_URL.rstrip('/')}/attributes/restSearch",
        headers={
            "Authorization": MISP_API_KEY,
            "Accept": "application/json",
            "Content-Type": "application/json",
        },
        json=body,
        verify=MISP_VERIFY_SSL,
        timeout=120,
    )
    if not response.ok:
        sys.exit(f"MISP returned HTTP {response.status_code}: {response.text[:300]}")
    return response.text.replace("\r\n", "\n")


def write_file(path, content):
    """Write with Unix line endings, even on Windows (the Linux containers read these files)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def timestamp():
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def export_pihole(days):
    text = misp_search("text", DOMAIN_TYPES, days)
    domains = sorted({line.strip().lower() for line in text.splitlines()})
    domains = [d for d in domains if DOMAIN_RE.match(d)]
    header = f"# MISP IOC domains - generated {timestamp()} - {len(domains)} entries\n"
    write_file(PIHOLE_LIST, header + "\n".join(domains) + ("\n" if domains else ""))
    print(f"Pi-hole:  {len(domains)} domains -> {PIHOLE_LIST}")
    for d in domains[:3]:
        print(f"          e.g. {d}")


def export_suricata(days):
    text = misp_search("suricata", DOMAIN_TYPES, days)
    rule_count = sum(1 for line in text.splitlines() if line.startswith("alert "))
    write_file(SURICATA_RULES, f"# MISP Suricata rules - generated {timestamp()}\n" + text)
    print(f"Suricata: {rule_count} rules -> {SURICATA_RULES}")


def reload_services():
    """Ask the running containers to pick up the new files."""
    for label, cmd in [
        ("Pi-hole gravity", ["docker", "exec", "pihole", "pihole", "-g"]),
        ("Suricata rules", ["docker", "exec", "suricata", "suricatasc", "-c", "reload-rules"]),
    ]:
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode == 0:
            print(f"Reload {label}: ok")
        else:
            print(f"Reload {label}: failed ({result.stderr.strip()[:200]})")


def main():
    parser = argparse.ArgumentParser(description="Export MISP IOCs to Pi-hole and Suricata")
    parser.add_argument("--days", type=int, help="only IOCs from events published in the last N days")
    parser.add_argument("--reload", action="store_true", help="reload Pi-hole and Suricata after writing")
    args = parser.parse_args()

    export_pihole(args.days)
    export_suricata(args.days)
    if args.reload:
        reload_services()


if __name__ == "__main__":
    main()
